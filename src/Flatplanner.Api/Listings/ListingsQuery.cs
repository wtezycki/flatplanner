using Flatplanner.Core.Search;
using Microsoft.AspNetCore.Mvc;

namespace Flatplanner.Api.Listings;

public sealed record ListingsQuery(
    [FromQuery] string[]? Cities,
    [FromQuery] string[]? Districts,
    int? PriceMin,
    int? PriceMax,
    decimal? AreaMin,
    decimal? AreaMax,
    decimal? AreaApprox,
    int? RoomsMin,
    int? RoomsMax,
    int? FloorMin,
    int? FloorMax,
    string? Market,
    string? AdvertiserType,
    int? BuildYearMin,
    int? BuildYearMax,
    int? PricePerM2Min,
    int? PricePerM2Max,
    int? RentMin,
    int? RentMax,
    string? FinishCondition,
    string? Ownership,
    string? BuildingType,
    string? Heating,
    string? BuildingMaterial,
    bool? RequireLift,
    bool? RequireBalcony,
    bool? RequireGarage,
    bool? RequireBasement,
    string? Text,
    [FromQuery] string[]? Preferences,
    string? RequestedCityOutOfScope,
    [FromQuery] string[]? OutOfScope,
    string? Sort,
    int? Page)
{
    public SearchIntent ToIntent() => new()
    {
        Cities = Cities ?? [],
        Districts = Districts ?? [],
        PriceMin = PriceMin,
        PriceMax = PriceMax,
        AreaMin = AreaMin,
        AreaMax = AreaMax,
        AreaApprox = AreaApprox,
        RoomsMin = RoomsMin,
        RoomsMax = RoomsMax,
        FloorMin = FloorMin,
        FloorMax = FloorMax,
        Market = Market,
        AdvertiserType = AdvertiserType,
        BuildYearMin = BuildYearMin,
        BuildYearMax = BuildYearMax,
        PricePerM2Min = PricePerM2Min,
        PricePerM2Max = PricePerM2Max,
        RentMin = RentMin,
        RentMax = RentMax,
        FinishCondition = FinishCondition,
        Ownership = Ownership,
        BuildingType = BuildingType,
        Heating = Heating,
        BuildingMaterial = BuildingMaterial,
        RequireLift = RequireLift ?? false,
        RequireBalcony = RequireBalcony ?? false,
        RequireGarage = RequireGarage ?? false,
        RequireBasement = RequireBasement ?? false,
        Text = Text,
        Preferences = Preferences ?? [],
        RequestedCityOutOfScope = RequestedCityOutOfScope,
        OutOfScope = OutOfScope ?? [],
    };
}
